import { NextResponse } from "next/server";
import { readFile } from "fs/promises";
import path from "path";

import { getSessionUser } from "@/lib/auth";
import { pool } from "@/lib/db";

type RouteContext = {
  params: Promise<{
    filename: string;
  }>;
};

export async function GET(
  _request: Request,
  { params }: RouteContext
) {
  try {
    // 1. Check whether the user is logged in.
    const sessionUser = await getSessionUser();

    if (!sessionUser) {
      return NextResponse.json(
        { message: "Please log in to view your resume." },
        { status: 401 }
      );
    }

    // 2. Only students can access this endpoint.
    if (sessionUser.role !== "Student") {
      return NextResponse.json(
        { message: "Only students can access this resource." },
        { status: 403 }
      );
    }

    // 3. Get the requested filename.
    const { filename } = await params;

    // Allow only UUID filenames generated by the upload API.
    const validFilename =
      /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(pdf|doc|docx)$/i;

    if (!validFilename.test(filename)) {
      return NextResponse.json(
        { message: "Invalid resume filename." },
        { status: 400 }
      );
    }

    // 4. Verify that this resume belongs to the logged-in student.
    const result = await pool.query(
      `SELECT resume_name, resume_url
       FROM users
       WHERE id = $1
         AND role = 'Student'
         AND is_active = TRUE`,
      [sessionUser.id]
    );

    if (result.rows.length === 0) {
      return NextResponse.json(
        { message: "Student profile not found." },
        { status: 404 }
      );
    }

    const student = result.rows[0];
    const expectedUrl = `/api/student/resume/file/${filename}`;

    if (student.resume_url !== expectedUrl) {
      return NextResponse.json(
        { message: "Resume not found or access denied." },
        { status: 404 }
      );
    }

    // 5. Read the file from the uploads directory.
    const uploadDirectory = path.join(
      process.cwd(),
      "uploads",
      "resumes"
    );

    const filePath = path.join(uploadDirectory, filename);
    const fileBuffer = await readFile(filePath);

    // 6. Determine the content type.
    const extension = path.extname(filename).toLowerCase();

    const contentTypes: Record<string, string> = {
      ".pdf": "application/pdf",
      ".doc": "application/msword",
      ".docx":
        "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    };

    const contentType =
      contentTypes[extension] || "application/octet-stream";

    // 7. Return the file to the authenticated student.
    // PDF files can open in the browser; Word files can be downloaded.
    const disposition =
      extension === ".pdf" ? "inline" : "attachment";

    return new Response(new Uint8Array(fileBuffer), {
      status: 200,
      headers: {
        "Content-Type": contentType,
        "Content-Disposition": `${disposition}; filename="resume${extension}"`,
        "Cache-Control": "private, no-store",
        "X-Content-Type-Options": "nosniff",
      },
    });
  } catch (error) {
    // A missing file is handled separately.
    if (
      error &&
      typeof error === "object" &&
      "code" in error &&
      error.code === "ENOENT"
    ) {
      return NextResponse.json(
        { message: "The uploaded resume file could not be found." },
        { status: 404 }
      );
    }

    console.error("Resume retrieval error:", error);

    return NextResponse.json(
      { message: "Unable to retrieve your resume right now." },
      { status: 500 }
    );
  }
}